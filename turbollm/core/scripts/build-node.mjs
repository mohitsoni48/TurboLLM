// Builds the napi addon (core/bindings/node), in one of two flavours (rust-core plan T10, T16; arch 2.1, 2.6, 4).
//
//   node core/scripts/build-node.mjs [--target <suffix>] [--release] [--cross-compile]
//   node core/scripts/build-node.mjs --flavour nodejs-mobile --libnode-dir <dir> --out <dir>
//                                    [--target android-arm64|android-x64] [--release]
//
// npm (default): builds for one npm target (default: this machine's, from targets.mjs), writes
// core/bindings/node/turbollm-core.<suffix>.node and regenerates src/native/binding.generated.d.ts.
// napi-rs's generated index.js loader is never written: src/native/load.ts is the only loader (arch A-3).
// --cross-compile (Linux targets only) builds through cargo-zigbuild (zig on PATH), a glibc target against
// GLIBC_FLOOR: how CI builds every Linux binary it ships (arch 2.7).
//
// nodejs-mobile: the addon the Android app's embedded Node loads. Built with cargo-ndk (ANDROID_NDK_HOME
// must name the NDK) and linked against nodejs-mobile's libnode.so, read from <libnode-dir>/<abi>/libnode.so.
// Writes <out>/<abi>/libturbollm_core_node.so for each ABI (both unless --target names one), then checks it
// with `cargo xtask check-android-elf --needs libnode.so`.
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { binaryFileName, crossCompileTriple, hostTarget, NPM_TARGETS } from './targets.mjs'

const CORE_DIR = join(dirname(fileURLToPath(import.meta.url)), '..')
const BINDING_DIR = join(CORE_DIR, 'bindings', 'node')
const TYPES_FILE = join(CORE_DIR, '..', 'src', 'native', 'binding.generated.d.ts')
const SCRATCH_TYPES_FILE = join(CORE_DIR, 'target', 'napi-types', 'binding.d.ts')
const TYPES_HEADER = '// generated by core/scripts/build-node.mjs; do not edit\n\n'
const USAGE_EXIT_CODE = 2
const FAILURE_EXIT_CODE = 1

/** The ABIs the APK ships; the suffixes name them on the command line. */
const NODEJS_MOBILE_TARGETS = Object.freeze([
  { suffix: 'android-arm64', triple: 'aarch64-linux-android', abi: 'arm64-v8a' },
  { suffix: 'android-x64', triple: 'x86_64-linux-android', abi: 'x86_64' },
])
const NODEJS_MOBILE_ADDON = 'libturbollm_core_node.so'
const ANDROID_MIN_API = '24'

const request = parseRequest(process.argv.slice(2))
if (request.flavour === 'npm') await buildNpmAddon(request)
else buildNodejsMobileAddons(request)

function parseRequest(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      target: { type: 'string' },
      release: { type: 'boolean', default: false },
      'cross-compile': { type: 'boolean', default: false },
      flavour: { type: 'string', default: 'npm' },
      'libnode-dir': { type: 'string' },
      out: { type: 'string' },
    },
  })
  if (values.flavour === 'npm') return npmRequest(values)
  if (values.flavour === 'nodejs-mobile') return nodejsMobileRequest(values)
  refuse(`unknown --flavour ${values.flavour}; use npm or nodejs-mobile`)
}

function npmRequest(values) {
  const suffix = values.target ?? hostSuffix()
  const target = NPM_TARGETS.find((candidate) => candidate.suffix === suffix)
  if (!target) refuse(`unknown --target ${suffix}; use one of ${suffixes(NPM_TARGETS)}`)
  const crossCompile = values['cross-compile']
  if (crossCompile && target.os !== 'linux') refuse(`--cross-compile is for the linux targets only, not ${suffix}`)
  return { flavour: 'npm', target, release: values.release, crossCompile }
}

function nodejsMobileRequest(values) {
  const targets = values.target
    ? NODEJS_MOBILE_TARGETS.filter((candidate) => candidate.suffix === values.target)
    : NODEJS_MOBILE_TARGETS
  if (targets.length === 0) refuse(`unknown --target ${values.target}; use one of ${suffixes(NODEJS_MOBILE_TARGETS)}`)
  if (!values['libnode-dir']) refuse('--flavour nodejs-mobile needs --libnode-dir <dir with <abi>/libnode.so>')
  if (!values.out) refuse('--flavour nodejs-mobile needs --out <dir>')
  return {
    flavour: 'nodejs-mobile',
    targets,
    release: values.release,
    libnodeDir: resolve(values['libnode-dir']),
    outDir: resolve(values.out),
  }
}

async function buildNpmAddon({ target, release, crossCompile }) {
  const { NapiCli } = await import('@napi-rs/cli')
  rmSync(dirname(SCRATCH_TYPES_FILE), { recursive: true, force: true })
  mkdirSync(dirname(SCRATCH_TYPES_FILE), { recursive: true })
  process.env.TURBOLLM_NPM_TARGET = target.suffix
  const { task } = await new NapiCli().build({
    cwd: BINDING_DIR,
    manifestPath: join(BINDING_DIR, 'Cargo.toml'),
    packageJsonPath: join(BINDING_DIR, 'package.json'),
    outputDir: BINDING_DIR,
    target: crossCompile ? crossCompileTriple(target) : target.triple,
    crossCompile,
    platform: true,
    noJsBinding: true,
    dts: relative(BINDING_DIR, SCRATCH_TYPES_FILE),
    noDtsHeader: true,
    release,
  })
  await task
  writeTypes()
  console.log(`built ${relative(process.cwd(), join(BINDING_DIR, binaryFileName(target.suffix)))}`)
}

/** LF endings and our own header, so the committed file is identical on every host. */
function writeTypes() {
  const generated = readFileSync(SCRATCH_TYPES_FILE, 'utf8').replace(/\r\n/g, '\n').trimStart()
  writeFileSync(TYPES_FILE, TYPES_HEADER + generated)
}

function buildNodejsMobileAddons(request) {
  for (const target of request.targets) {
    const addon = buildNodejsMobileAddon(target, request)
    cargo(['run', '--quiet', '-p', 'xtask', '--', 'check-android-elf', addon, '--needs', 'libnode.so'])
    console.log(`built ${addon}`)
  }
}

/**
 * Without the default `dyn-symbols` feature the addon imports `napi_*` as ordinary undefined symbols, which the
 * `libnode.so` NEEDED entry resolves; `dyn-symbols` would look them up in the app process instead, where
 * nodejs-mobile's libnode.so is not visible.
 */
function buildNodejsMobileAddon(target, { release, libnodeDir, outDir }) {
  const libnodeAbiDir = join(libnodeDir, target.abi)
  if (!existsSync(join(libnodeAbiDir, 'libnode.so'))) fail(`no libnode.so in ${libnodeAbiDir}`)
  const profile = release ? ['--release'] : []
  cargo(
    ['ndk', '-t', target.abi, '--platform', ANDROID_MIN_API, 'build', '-p', 'turbollm-node',
      '--no-default-features', '--features', 'nodejs-mobile', ...profile],
    { TURBOLLM_LIBNODE_DIR: libnodeAbiDir },
  )
  const built = join(CORE_DIR, 'target', target.triple, release ? 'release' : 'debug', 'libturbollm_node.so')
  const addon = join(outDir, target.abi, NODEJS_MOBILE_ADDON)
  mkdirSync(dirname(addon), { recursive: true })
  copyFileSync(built, addon)
  return addon
}

function cargo(args, env = {}) {
  const run = spawnSync('cargo', args, { cwd: CORE_DIR, env: { ...process.env, ...env }, stdio: 'inherit' })
  if (run.error) fail(`cargo ${args[0]}: ${run.error.message}`)
  if (run.status !== 0) fail(`cargo ${args.join(' ')} exited ${run.status}`)
}

function hostSuffix() {
  const host = hostTarget()
  if (!host) refuse(`no npm target for this machine (${process.platform}-${process.arch}); pass --target`)
  return host.suffix
}

function suffixes(targets) {
  return targets.map((t) => t.suffix).join(', ')
}

function refuse(message) {
  console.error(`build-node: ${message}`)
  process.exit(USAGE_EXIT_CODE)
}

function fail(message) {
  console.error(`build-node: ${message}`)
  process.exit(FAILURE_EXIT_CODE)
}
